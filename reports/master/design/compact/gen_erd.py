"""Split ERD_JobQuest_Chen.puml into six smaller Chen diagrams ERD-01 … ERD-06.

The single file stays the source of truth (gen_domain.py and gen_class.py read it too).
This script only reads it and writes plantuml/erd/ERD-0n_*.puml. Edit the source, then rerun.

Split rules:
  - each entity has one home diagram (its section); only there is it drawn with every attribute;
  - an entity from another diagram is drawn as a stub with its key attributes only, and listed
    in the title as "borrowed" with its home diagram;
  - each relationship is drawn once, in the diagram of the section that declares it.
"""
from pathlib import Path

from erd_parse import ERD, parse_erd

OUT = ERD.parent

DIAGRAMS = [
    ("ERD-01", "IdentityQualityAndAiOps", "Identity, grading quality, feedback and AI operations", "AL"),
    ("ERD-02", "CatalogueReferenceAndKeywords", "Occupation catalogue, reference data, soft skills and keywords", "BC"),
    ("ERD-03", "LevelPackAndScenarioContent", "Level pack and scenario content", "DE"),
    ("ERD-04", "AuthoringReviewAndRelease", "AI drafting, review, presentation, play-test and release", "F"),
    ("ERD-05", "NpcEconomyAndLife", "Tarot NPCs, side quests, economy, health and calendar", "GK"),
    ("ERD-06", "ExplorerProgressRunsAndGrading", "Explorer profile, progression, runs and grading", "HIJ"),
]

SECTION_TITLE = {
    "A": "Identity and assignment", "B": "Catalogue, occupation profile, work environments",
    "C": "Reference data, soft skill, keyword, grading library", "D": "Level pack",
    "E": "Scenario content", "F": "AI drafting, review, presentation, play-test, release",
    "G": "Tarot NPCs, side quests, character assets", "H": "Explorer profile", "I": "Progression",
    "J": "Runs and grading", "K": "Economy, health, calendar, NPC relationship",
    "L": "Grading quality, feedback, AI operations",
}


def home_of(section):
    for did, _, _, secs in DIAGRAMS:
        if section in secs:
            return did
    raise ValueError(section)


def stereo(a):
    s = []
    if a.get("key"):
        s.append("<<key>>")
    if a.get("multi"):
        s.append("<<multi>>")
    if a.get("derived"):
        s.append("<<derived>>")
    return (" " + " ".join(s)) if s else ""


def attr_lines(attrs, indent="  "):
    out = []
    for a in attrs:
        if a["group"]:
            out.append(f"{indent}{a['name']}{stereo(a)} {{")
            out += [f"{indent}  {c['name']}{stereo(c)}" for c in a["children"]]
            out.append(f"{indent}}}")
        else:
            out.append(f"{indent}{a['name']}{stereo(a)}")
    return out


def comment_lines(rec):
    out = []
    if rec.get("tag"):
        out.append(f"' [{rec['tag']}] {rec.get('note') or ''}".rstrip())
    elif rec.get("note"):
        out.append(f"' {rec['note']}")
    return out


def block(kind, name, stereos, attrs):
    head = f"{kind} {name}{(' ' + ' '.join(stereos)) if stereos else ''} {{"
    if not attrs:
        return [head + " }"]
    return [head] + attr_lines(attrs) + ["}"]


def link_line(end, rel, first):
    line = "=" if end["total"] else "-"
    lab = end["label"]
    if first:
        return f"{end['entity']} {line}{lab}{line} {rel}"
    return f"{rel} {line}{lab}{line} {end['entity']}"


def build(did, slug, title, secs, entities, relationships, isa):
    own_e = [e for e in entities.values() if e["section"] in secs]
    own_r = [r for r in relationships.values() if r["section"] in secs]
    own_names = {e["name"] for e in own_e}
    used = []
    for r in own_r:
        for end in r["ends"]:
            if end["entity"] not in own_names and end["entity"] not in used:
                used.append(end["entity"])
    borrowed = sorted(used, key=lambda n: (home_of(entities[n]["section"]), n))

    out = [f"@startchen {did}_{slug}"]
    btxt = ", ".join(f"{n} ({home_of(entities[n]['section'])})" for n in borrowed)
    sub = f"\\n<size:11>Borrowed, key only: {btxt}</size>" if borrowed else ""
    out.append(f"title {did} · {title} (Chen){sub}")
    out += [
        "' GENERATED by reports/master/design/compact/gen_erd.py from plantuml/erd/ERD_JobQuest_Chen.puml.",
        "' Do not edit this file: edit ERD_JobQuest_Chen.puml and rerun the script.",
        f"' Sections: {', '.join(f'{s}. {SECTION_TITLE[s]}' for s in secs)}",
        "' Notation: <<weak>> double rectangle · <<identifying>> double diamond · <<key>> key (partial on weak)",
        "'   <<derived>> dashed oval · <<multi>> double oval · { } composite · =N= total participation",
        "'   Label next to an entity = that entity's cardinality in the relationship.",
        "' [CAM] research still 'can chot' or draft (07 A28) · [VANG] research 'da chot', no D-ID yet",
        "",
    ]
    for s in secs:
        out.append(f"' ═══ {s}. {SECTION_TITLE[s]} ═══")
        for e in [x for x in own_e if x["section"] == s]:
            out += comment_lines(e)
            out += block("entity", e["name"], ["<<weak>>"] if e["weak"] else [], e["attrs"])
        for r in [x for x in own_r if x["section"] == s]:
            out += comment_lines(r)
            out += block("relationship", r["name"], ["<<identifying>>"] if r["identifying"] else [], r["attrs"])
        out.append("")
    if borrowed:
        out.append("' ═══ Borrowed from other diagrams (key attributes only) ═══")
        for n in borrowed:
            e = entities[n]
            out.append(f"' home: {home_of(e['section'])}")
            out += block("entity", n, ["<<weak>>"] if e["weak"] else [], [a for a in e["attrs"] if a["key"]])
        out.append("")
    out.append("' ═══ Links ═══")
    for i in isa:
        if i["parent"] in own_names:
            line = "=" if i["total"] else "-"
            out.append(f"{i['parent']} {line}>{line} {'o' if i['overlap'] else 'd'} {{ {', '.join(i['children'])} }}")
    for r in own_r:
        for k, end in enumerate(r["ends"]):
            out.append(link_line(end, r["name"], k == 0))
    out += ["", "@endchen", ""]
    path = OUT / f"{did}_{slug}.puml"
    path.write_text("\n".join(out), encoding="utf-8")
    return path, len(own_e), len(own_r), len(borrowed)


def main():
    entities, relationships, isa = parse_erd()
    for p in OUT.glob("ERD-0*_*.puml"):
        p.unlink()
    total_e = total_r = 0
    for did, slug, title, secs in DIAGRAMS:
        path, ne, nr, nb = build(did, slug, title, secs, entities, relationships, isa)
        total_e += ne
        total_r += nr
        print(f"{path.name}: {ne} entities, {nr} relationships, {nb} borrowed")
    assert total_e == len(entities) and total_r == len(relationships), "every item must have one home"
    print(f"total {total_e}/{len(entities)} entities, {total_r}/{len(relationships)} relationships")


if __name__ == "__main__":
    main()
